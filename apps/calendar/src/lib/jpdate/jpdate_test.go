package jpdate

import "testing"

// 2026-10-05 12:00:00 JST（月曜日）
const now = 1791169200

func TestParse(t *testing.T) {
	tests := []struct {
		in   string
		want string // DateTime（JST）、解釈できないなら ""
		unix int
	}{
		// 年月日
		{"2026年10月1日", "2026-10-01 00:00:00", 1790780400},
		{"10月1日", "2026-10-01 00:00:00", 1790780400},
		{"1日", "2026-10-01 00:00:00", 1790780400},
		{"2026年2月30日", "", 0},
		{"2026年1日", "2026-10-01 00:00:00", 1790780400},
		{"123日", "", 0},
		// 区切り
		{"2026/10/1", "2026-10-01 00:00:00", 1790780400},
		{"26/10/1", "2026-10-01 00:00:00", 1790780400},
		{"60/1/1", "1960-01-01 00:00:00", -315651600},
		{"10/1", "2026-10-01 00:00:00", 1790780400},
		{"10-1", "2026-10-01 00:00:00", 1790780400},
		{"2026/10-01", "", 0},
		{"123/1/1", "", 0},
		{"2024/2/29", "2024-02-29 00:00:00", 1709132400},
		{"2023/2/29", "", 0},
		// 8 桁・6 桁
		{"20261001", "2026-10-01 00:00:00", 1790780400},
		{"261001", "2026-10-01 00:00:00", 1790780400},
		{"20261301", "", 0},
		{"00000101", "", 0},
		// ISO 8601
		{"2026-10-01", "2026-10-01 00:00:00", 1790780400},
		{"2026", "2026-01-01 00:00:00", 1767193200},
		{"2026-10", "2026-10-01 00:00:00", 1790780400},
		{"2026-10-01T12:00:00Z", "2026-10-01 21:00:00", 1790856000},
		{"2026-10-01T12:00:00-05:00", "2026-10-02 02:00:00", 1790874000},
		{"2026-10-01t12:00z", "2026-10-01 21:00:00", 1790856000},
		{"2026-10-01T1200", "2026-10-01 12:00:00", 1790823600},
		{"2026-10-01T12:00:00.999", "2026-10-01 12:00:00", 1790823600},
		{"2026-10-01T24:00", "2026-10-02 00:00:00", 1790866800},
		{"2026-10-01T24:00:00.001", "", 0},
		{"2026-10-01T23:60", "", 0},
		{"2026-10-01Z", "", 0},
		{"2026-W40-4", "2026-10-01 00:00:00", 1790780400},
		{"2026-W40", "2026-09-28 00:00:00", 1790521200},
		{"2026-W53", "2026-12-28 00:00:00", 1798383600},
		{"2027-W53", "", 0},
		{"2020-W53-7", "2021-01-03 00:00:00", 1609599600},
		{"2026-274", "2026-10-01 00:00:00", 1790780400},
		{"2026-366", "", 0},
		{"12:00", "2026-10-05 12:00:00", 1791169200},
		{"23:59:59Z", "2026-10-06 08:59:59", 1791244799},
		{"+010000-01-01", "10000-01-01 00:00:00", 253402268400},
		{"+275760-09-14", "", 0},
		// 西暦 1 年より前は扱わない
		{"0001-01-01", "0001-01-01 00:00:00", -62135629200},
		{"0001-01-01T08:59:59Z", "0001-01-01 17:59:59", -62135564401},
		{"0000-12-31T15:00:00Z", "0001-01-01 00:00:00", -62135629200},
		{"0000-12-31T14:59:59Z", "", 0},
		// IANA のタイムゾーン名は扱わない
		{"2026-10-01T12:00:00Z[Asia/Tokyo]", "", 0},
		{"hello", "", 0},
	}
	for _, tt := range tests {
		info, ok := ParseDate(tt.in, now)
		got := ""
		if ok {
			got = info.DateTime
		}
		if got != tt.want || ok && info.UnixTime != tt.unix {
			t.Errorf("ParseDate(%q) = %q (%d), want %q (%d)", tt.in, got, info.UnixTime, tt.want, tt.unix)
		}
	}
}

func TestFormat(t *testing.T) {
	info, ok := ParseDate("2026-10-01", now)
	if !ok {
		t.Fatal("ParseDate failed")
	}
	if got, want := info.Weekday, "木曜日"; got != want {
		t.Errorf("Weekday = %q, want %q", got, want)
	}
	if got, want := info.Japanese, "2026年10月01日(木)"; got != want {
		t.Errorf("Japanese = %q, want %q", got, want)
	}
	if got, want := info.ISODate, "2026-10-01"; got != want {
		t.Errorf("ISODate = %q, want %q", got, want)
	}

	big, _ := ParseDate("+010000-01-01", now)
	if got, want := big.ISODate, "+010000-01-01"; got != want {
		t.Errorf("ISODate = %q, want %q", got, want)
	}
	if got, want := Today(now), "2026-10-05"; got != want {
		t.Errorf("Today() = %q, want %q", got, want)
	}
}
